// Rng — генератор псевдослучайных чисел ядра (mulberry32). Одно зерно — одна и та же
// последовательность на любой машине: мир звучит одинаково в вебе, в приложении и в тестах,
// а снимок восстанавливается точно.
//
// Бит в бит как rnd() в tools/ref/pulsar-worklet.js (Math.imul в JS — обычное умножение uint32 здесь).
//
// ЛОВУШКИ:
//   - next() даёт [0, 1): ровно 1 не выпадает никогда.
//   - В модели мира — только Rng: rand(), std::random и Math.random зависят от платформы.
//   - Всё состояние — одно число state: сохранил его — продолжишь ту же последовательность.
// Цена — десяток целочисленных операций.
#pragma once
#include <cstdint>

namespace sdk {

struct Rng {
  uint32_t state;
  explicit Rng(uint32_t seed) : state(seed) {}

  double next() {                                       // [0, 1); константы и порядок — mulberry32, не трогать
    state += 0x6D2B79F5u;
    uint32_t t = state;
    t = (t ^ (t >> 15)) * (t | 1u);
    t ^= t + (t ^ (t >> 7)) * (t | 61u);
    return (t ^ (t >> 14)) / 4294967296.0;
  }
};

}  // namespace sdk
