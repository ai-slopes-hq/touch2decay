// DcBlock — убирает постоянную составляющую: сдвиг сигнала от нуля, который дают несимметричный
// перегруз, выпрямление, шум с ненулевым средним. Без него сдвиг съедает запас до клиппинга
// и щёлкает, когда звук включается и выключается.
//
//   y = x − x_прошлый + R·y_прошлый
//
// Это фильтр верхних частот первого порядка: ноль на 0 Гц, полюс в R. R = 0.995, как в прежних
// worklet-ах: срез ≈ sr·(1 − R)/2π ≈ 38 Гц при 48 кГц.
//
// ЛОВУШКИ:
//   - R ближе к 1 — срез ниже, но сдвиг уходит дольше. R ≥ 1 — фильтр неустойчив.
//   - Частоту дискретизации блок не знает: R = 0.995 подобран под 48 кГц.
// Цена — умножение и два сложения на сэмпл.
#pragma once

namespace sdk {

struct DcBlock {
  double R = 0.995;
  double previousInput = 0, previousOutput = 0;

  double step(double x) {
    double y = x - previousInput + R * previousOutput;
    previousInput = x; previousOutput = y;
    return y;
  }
};

}  // namespace sdk
